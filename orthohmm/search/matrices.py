def get_background_freqs(matrix_name: str) -> np.ndarray:
    """Return background amino acid frequencies for a matrix family."""
    if matrix_name.startswith("PAM"):
        return DAYHOFF_FREQS.copy()
    if matrix_name == "WAG":
        return WAG_FREQS.copy()
    if matrix_name == "LG":
        return LG_FREQS.copy()
    return ROBINSON_ROBINSON_FREQS.copy()


