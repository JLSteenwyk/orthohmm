"""Audit a fresh hash-locked recovery environment and its installed package bytes."""

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import subprocess
import zipfile

from benchmark_tools.audit_frozen_overlay_install import local_install_wheels, scientific_members
from benchmark_tools.audit_leiden_recovery_wheel import audit as leiden_audit
from benchmark_tools.prepare_ob_candidate_neighborhood import check, record
from benchmark_tools.verify_frozen_source_archive import git_files


def installed_payload(wheel, site):
    matched, excluded = [], []
    with zipfile.ZipFile(wheel) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)):
            raise ValueError("Duplicate archive entries")
        for name in names:
            path = PurePosixPath(name)
            if path.is_absolute() or ".." in path.parts or "\\" in name:
                raise ValueError("Unsafe wheel member")
            if name.endswith("/"):
                continue
            if path.parts[0].endswith(".data"):
                excluded.append(dict(member=name, reason="relocated non-site payload, not checked here"))
                continue
            if len(path.parts) == 2 and name.endswith(".dist-info/RECORD"):
                excluded.append(dict(member=name, reason="installer-generated RECORD, not archive bytes"))
                continue
            if path.suffix == ".pyc" and path.parent.name == "__pycache__":
                source = path.parent.parent / (path.name.split(".")[0] + ".py")
                if source.as_posix() not in names:
                    raise ValueError("Bundled bytecode lacks auditable source")
                excluded.append(dict(member=name, reason="installer-regenerated bytecode; source checked separately"))
                continue
            target = site / name
            if not target.resolve().is_relative_to(site.resolve()) or target.is_symlink():
                raise ValueError("Installed member escapes site")
            data = archive.read(name)
            actual = target.read_bytes()
            if actual != data:
                raise ValueError("Installed payload differs: " + name)
            matched.append(dict(member=name, bytes=len(data), sha256=hashlib.sha256(data).hexdigest()))
    return dict(matched_files=len(matched), matched=matched, excluded=excluded)


def audit(repo, directory):
    paths = [directory / n for n in ("preparation.json", "install_report.json", "smoke/verification.json")]
    preparation, installation, smoke = [json.loads(p.read_text()) for p in paths]
    checked = [record(p) for p in paths]
    for item in [preparation["previous_install"], preparation["leiden_acquisition"], preparation["lock"],
                 *preparation["sources"], *preparation["wheels"]]:
        check(item)
        checked.append(item)
    wheels = local_install_wheels(installation, directory / "wheels")
    expected = {(r["metadata"]["name"].lower().replace("-", "_"), r["metadata"]["version"])
                for r in installation["install"]}
    observed = {(r["name"].lower().replace("-", "_"), r["version"]) for r in smoke["runtime"]["dependencies"]}
    if len(wheels) != 11 or expected != observed or ("leidenalg", "0.11.0") not in expected:
        raise ValueError("Installed distribution inventory differs")
    if smoke["status"] != "same_host_cpu_wheel_smoke_verified":
        raise ValueError("Missing successful installed smoke")
    site = Path(smoke["runtime"]["module"]).parent.parent
    if not site.is_relative_to(directory / "venv"):
        raise ValueError("Smoke escaped new environment")
    package_rows = []
    for row in wheels:
        package_rows.append(dict(name=row["name"], version=row["version"], wheel=row["wheel"],
                                 **installed_payload(Path(row["wheel"]["path"]), site)))
    wheel = Path(smoke["wheel"]["path"])
    scientific = scientific_members(wheel, git_files(repo))
    leiden = next(Path(r["wheel"]["path"]) for r in wheels if r["name"].lower() == "leidenalg")
    dependency = leiden_audit(repo, leiden)
    python = directory / "venv/bin/python"
    pip_check = subprocess.check_output([str(python), "-I", "-m", "pip", "check"], text=True, timeout=60)
    for item in [*smoke["installed"], *smoke["inputs"], *smoke["original_inputs"],
                 *[r["partition"] for r in smoke["runs"]], *[r["log"] for r in smoke["runs"]]]:
        check(item)
        checked.append(item)
    return dict(status="fresh_recovery_environment_package_payload_and_smoke_verified", source=record(__file__),
        checked_records=checked, wheels=package_rows, scientific_members=scientific,
        leiden_snapshot=dependency, runtime=smoke["runtime"], runs=smoke["runs"], pip_check=pip_check,
        full_dataset_reproduced=False, phylogeny_executed=False, publication_ready=False,
        limitations=["Same-host clean installation and 38-gene standard/high-sensitivity smoke, not full benchmark reproduction.",
            "Non-site wheel data and generated RECORD/entrypoint/bytecode files are not asserted byte-identical.",
            "External MAFFT/FastTree tools, canonical-order policy integration and cross-platform validation remain separate."])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("repo", "directory", "output"):
        parser.add_argument("--" + name, type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError(args.output)
    result = audit(args.repo.resolve(), args.directory.resolve())
    with args.output.open("x") as stream:
        json.dump(result, stream, indent=2, sort_keys=True)
        stream.write("\n")
